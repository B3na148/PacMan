	public void draw_map(PApplet app) {
		int x = 0;
		int y = 0;
		for (int i = 0; i < map1.length; i ++) {	
			for (int j = 0; j < map1[i].length; j ++) {
				if (map1[i][j] == 1)app.fill(255,0,0);
				if (map1[i][j] == 0)app.fill(0,0,0);
				if (map1[i][j] == 2)app.fill(0,255,0);
				if (map1[i][j] < 0)app.fill(255,255,255);
				app.rect(x,y,40,40);
				x += 40;}
			y += 40;
			x = 0;
			}
	}
	
	
